using System.Text;
using System.Text.Json;
using AxiosNet.Cli.Model;

namespace AxiosNet.Cli.Generation;

/// <summary>
/// 落地生成结果：覆盖保护、失联文件清理、<c>--check</c> / <c>--dry-run</c> 都集中在这里。
/// 生成文件一律 LF + 无 BOM，保证 Windows / Linux 上产出逐字节一致。
/// </summary>
internal static class OutputWriter
{
    /// <summary>生成文件首行标记，用于区分「本工具产出」与用户手写文件。</summary>
    private const string Marker = "// <auto-generated />";

    /// <summary>文件头里的工具签名，与 <see cref="Marker"/> 一起构成覆盖 / 删除的判定条件。</summary>
    private const string ToolMarker = "// Generated by axiosnet-gen";

    /// <summary>上次生成文件清单的固定文件名（与生成文件同目录）。</summary>
    public const string ManifestName = "axiosnet-gen.manifest.json";

    /// <summary>落盘主流程：清理失联文件、接管清单，再按 <c>--dry-run</c> / <c>--check</c> / 正常写入分派。</summary>
    public static int Apply(
        CliOptions options,
        IReadOnlyList<GeneratedFile> files,
        Func<IReadOnlyCollection<string>, GeneratedFile> manifestFactory,
        ICollection<ApiWarning> warnings)
    {
        // 输出目录统一成绝对路径，后续都用它拼文件路径。
        var directory = Path.GetFullPath(options.OutputDirectory);

        // 本次要生成的文件名（不含清单），用来判断上次清单里哪些文件已失联。
        var generatedNames = files.Select(file => file.Name).ToHashSet(StringComparer.Ordinal);

        // 上次清单记录的文件；读不到或损坏时返回空表并追加警告；Invalid 表示清单存在但无法解析。
        var (previous, manifestInvalid) = ReadManifest(directory, warnings);

        // 没加 --force 时旧文件删不掉，但必须继续留在清单里：否则下次清单重写后它就彻底失联。
        var stale = new List<string>();

        // --force 待删除的旧生成文件：延后到本次写盘成功之后才真正删除，
        // 否则生成中途失败（例如覆盖保护抛错）会留下「旧文件已删、新文件未写」的半成品目录。
        var deletions = new List<string>();
        foreach (var name in previous)
        {
            if (name == ManifestName || generatedNames.Contains(name))
            {
                continue;
            }

            var path = Path.Combine(directory, name);
            if (!File.Exists(path))
            {
                continue;
            }

            if (options.Force && !options.DryRun && !options.Check && HasMarker(ReadUtf8(path)))
            {
                deletions.Add(name);
                continue;
            }

            stale.Add(name);
        }

        // 新清单 = 本次生成 + 仍在盘上的失联文件（排序后保证 JSON 内容稳定）。
        var tracked = generatedNames.Concat(stale).OrderBy(name => name, StringComparer.Ordinal).ToList();

        // 实际参与 dry-run / check / 写入的全部文件，末尾追加清单本身。
        var output = files.Append(manifestFactory(tracked)).ToList();

        if (options.DryRun)
        {
            foreach (var file in output)
            {
                Console.WriteLine($"// ==== {file.Name} ====");
                Console.Write(file.Content);
                if (!file.Content.EndsWith('\n'))
                {
                    Console.WriteLine();
                }
            }

            return 0;
        }

        if (options.Check)
        {
            return Check(directory, output, stale);
        }

        Directory.CreateDirectory(directory);

        foreach (var file in output)
        {
            var path = Path.Combine(directory, file.Name);
            if (!File.Exists(path))
            {
                continue;
            }

            // 必须保留 BOM：File.ReadAllText 会自动吞掉 U+FEFF，导致带 BOM 的文件被误判为「已是最新」，
            // --check 永远通过、也永远不重写，违反「UTF-8 无 BOM」的产出约定。
            var existing = ReadUtf8(path);
            if (NormalizeLf(existing) == file.Content)
            {
                continue;
            }

            if (!IsOwnedFile(file.Name, existing, manifestInvalid) && !options.Force)
            {
                throw new GenerationException(
                    $"目标文件已存在且不是 axiosnet-gen 生成的：{path}（加 --force 覆盖）。");
            }
        }

        foreach (var name in stale)
        {
            warnings.Add(new ApiWarning(
                "STALE_FILE",
                name,
                "上次生成的文件本次不再生成；加 --force 可删除。"));
        }

        // 只写入内容有变化的文件，避免无意义地刷新时间戳。
        var written = 0;
        foreach (var file in output)
        {
            var path = Path.Combine(directory, file.Name);
            if (File.Exists(path) && NormalizeLf(ReadUtf8(path)) == file.Content)
            {
                continue;
            }

            File.WriteAllText(path, file.Content, new UTF8Encoding(false));
            written++;
        }

        // 写盘成功后才删除失联文件，避免半途失败时旧产物已经丢了。
        foreach (var name in deletions)
        {
            File.Delete(Path.Combine(directory, name));
            Console.WriteLine($"  removed stale: {name}");
        }

        Console.WriteLine($"  写入 {written} 个文件（共 {output.Count} 个）到 {directory}。");
        return 0;
    }

    /// <summary><c>--check</c> 实现：只比对不写入，返回 0 表示一致、1 表示有缺失 / 过期 / 失联文件。</summary>
    private static int Check(string directory, IReadOnlyList<GeneratedFile> files, List<string> stale)
    {
        // 待报告的问题描述（missing / out of date / stale）。
        var problems = new List<string>();

        foreach (var file in files)
        {
            var path = Path.Combine(directory, file.Name);
            if (!File.Exists(path))
            {
                problems.Add($"missing: {file.Name}");
            }
            else if (NormalizeLf(ReadUtf8(path)) != file.Content)
            {
                problems.Add($"out of date: {file.Name}");
            }
        }

        foreach (var name in stale)
        {
            problems.Add($"stale: {name}");
        }

        if (problems.Count == 0)
        {
            Console.WriteLine($"  输出已是最新（{files.Count} 个文件）。");
            return 0;
        }

        foreach (var problem in problems)
        {
            Console.WriteLine($"  {problem}");
        }

        Console.WriteLine($"--check 失败：{problems.Count} 个文件与生成结果不一致（未写入）。");
        return 1;
    }

    /// <summary>
    /// 读取上次生成的清单文件：不存在返回空表；JSON 损坏或读写失败时记警告并返回空表，
    /// 同时把 <c>Invalid</c> 置位，表示这份清单是「坏的旧文件」，允许按本工具所有直接覆盖。
    /// </summary>
    private static (List<string> Files, bool Invalid) ReadManifest(string directory, ICollection<ApiWarning> warnings)
    {
        var path = Path.Combine(directory, ManifestName);
        if (!File.Exists(path))
        {
            return (new List<string>(), false);
        }

        try
        {
            // 清单按 UTF-8 原始字节读取（存 BOM 时手工剥掉），避免 StreamReader 的 BOM 处理掩盖内容差异。
            var content = ReadUtf8(path);
            if (content.Length > 0 && content[0] == '\uFEFF')
            {
                content = content[1..];
            }

            using var document = JsonDocument.Parse(content);

            // 只接受合法的相对文件名，防止清单被篡改成路径穿越；同名重复项直接忽略，
            // 否则 stale / --check 报告与重写后的清单都会出现重复条目。
            var result = new List<string>();
            var seen = new HashSet<string>(StringComparer.Ordinal);

            // 合法 JSON 但缺少 files 数组说明这份清单不是本工具写的：按损坏处理，
            // 否则会把已经生成的旧文件全部当成失联，反而破坏覆盖保护。
            if (!document.RootElement.TryGetProperty("files", out var files)
                || files.ValueKind != JsonValueKind.Array)
            {
                throw new JsonException("清单缺少 files 数组。");
            }

            foreach (var item in files.EnumerateArray())
            {
                if (item.ValueKind == JsonValueKind.String
                    && item.GetString() is { } name
                    && IsSafeFileName(name)
                    && seen.Add(name))
                {
                    result.Add(name);
                }
            }

            return (result, false);
        }
        catch (Exception ex) when (ex is JsonException or IOException or UnauthorizedAccessException)
        {
            // 清单损坏或读不出来时不能按首次生成处理：否则下次写清单会覆盖保护失败，用户被迫加 --force。
            warnings.Add(new ApiWarning("MANIFEST_INVALID", ManifestName, $"无法读取上次生成的清单：{ex.Message}"));
            return (new List<string>(), true);
        }
    }

    /// <summary>判断清单里的名字是否是安全的相对文件名：非空、非 . / ..、不含路径分隔符且非绝对路径。</summary>
    private static bool IsSafeFileName(string name)
        => name.Length > 0
           && name != "."
           && name != ".."
           && name.IndexOfAny(new[] { '/', '\\' }) < 0
           && !Path.IsPathRooted(name);

    /// <summary>判断文件内容是否带本工具的生成标记（首行标记 + 工具签名同时满足；容忍文件被加过 BOM）。</summary>
    private static bool HasMarker(string content)
    {
        if (content.Length > 0 && content[0] == '\uFEFF')
        {
            content = content[1..];
        }

        return content.StartsWith(Marker, StringComparison.Ordinal)
               && content.Contains(ToolMarker, StringComparison.Ordinal);
    }

    /// <summary>
    /// 清单是 JSON，写不进注释标记；用固定文件名 + 固定的 generator 字段识别为本工具所有，
    /// 否则文件集合变化时清单永远无法按正常流程更新。清单上次读取失败（损坏）时同样视为可覆盖。
    /// </summary>
    private static bool IsOwnedFile(string name, string content, bool manifestInvalid)
    {
        if (HasMarker(content))
        {
            return true;
        }

        if (name != ManifestName)
        {
            return false;
        }

        if (manifestInvalid)
        {
            return true;
        }

        // 用 JsonDocument 精确读取 generator 字段：子串匹配会被紧凑格式（无空格）或字段顺序变化骗过。
        try
        {
            if (content.Length > 0 && content[0] == '\uFEFF')
            {
                content = content[1..];
            }

            using var document = JsonDocument.Parse(content);
            return document.RootElement.ValueKind == JsonValueKind.Object
                   && document.RootElement.TryGetProperty("generator", out var generator)
                   && generator.ValueKind == JsonValueKind.String
                   && generator.GetString() is { } value
                   && value.StartsWith("axiosnet-gen/", StringComparison.Ordinal);
        }
        catch (JsonException)
        {
            return false;
        }
    }

    /// <summary>按 UTF-8 读取文件并保留 BOM（<see cref="File.ReadAllText(string)"/> 会静默吞掉它）。</summary>
    private static string ReadUtf8(string path)
        => Encoding.UTF8.GetString(File.ReadAllBytes(path));

    /// <summary>把 CRLF 统一成 LF，使 Windows 上检出的文件也能与生成内容逐字节比较。</summary>
    private static string NormalizeLf(string content)
        => content.Replace("\r\n", "\n", StringComparison.Ordinal);
}
