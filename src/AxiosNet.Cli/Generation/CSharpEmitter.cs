using System.Globalization;
using System.Text;
using AxiosNet.Cli.Model;

namespace AxiosNet.Cli.Generation;

/// <summary>一个待落盘的生成文件：<paramref name="Name"/> 为相对文件名（含 .g.cs），<paramref name="Content"/> 为完整源码文本。</summary>
internal sealed record GeneratedFile(string Name, string Content);

/// <summary>把 IR 排成确定性的 C# 源码：模型一个文件（或并入单文件），接口式每组一个接口文件、模型式每组一个请求模型文件。</summary>
internal sealed class CSharpEmitter
{
    /// <summary>归一化后的 API，提供模型、分组与操作。</summary>
    private readonly ApiSpec _spec;

    /// <summary>命令行选项，决定命名空间、生成形态、单文件与响应包装等输出细节。</summary>
    private readonly CliOptions _options;

    /// <summary>工具版本号，写进文件头注释，便于追溯是哪一版生成器产出的代码。</summary>
    private readonly string _toolVersion;

    /// <summary>构造发射器；输出内容只由这三个入参决定，不读取环境状态。</summary>
    public CSharpEmitter(ApiSpec spec, CliOptions options, string toolVersion)
    {
        _spec = spec;
        _options = options;
        _toolVersion = toolVersion;
    }

    /// <summary>按选项渲染全部文件：单文件模式合并输出，否则模型与各分组分别成文件。</summary>
    public IReadOnlyList<GeneratedFile> Emit()
    {
        // 待落盘文件集合，顺序固定（模型在前、分组按读取阶段的顺序）。
        var files = new List<GeneratedFile>();

        if (_options.SingleFile)
        {
            var builder = NewFileBuilder();
            AppendModels(builder);

            foreach (var group in _spec.Groups)
            {
                AppendGroup(builder, group);
            }

            // 单文件下接口式且只有一个接口时用接口名做文件名，其余情况统一叫 ApiClient。
            var name = _options.Style == ApiStyle.Interface && _options.SingleInterface
                ? _options.InterfaceName + ".g.cs"
                : "ApiClient.g.cs";
            files.Add(new GeneratedFile(name, builder.ToString()));
            return files;
        }

        // 分文件模式：模型单独落 Models.g.cs，没有任何可复用类型时省略该文件。
        if (_spec.Types.Count > 0)
        {
            var builder = NewFileBuilder();
            AppendModels(builder);
            files.Add(new GeneratedFile("Models.g.cs", builder.ToString()));
        }

        foreach (var group in _spec.Groups)
        {
            if (_options.Style == ApiStyle.Model && group.Operations.Count == 0)
            {
                continue;
            }

            var builder = NewFileBuilder();
            AppendGroup(builder, group);

            // 模型式用请求模型文件名（如 PetsRequests），接口式用接口名（如 IUsersApi）。
            var fileName = _options.Style == ApiStyle.Model ? group.RequestFileName : group.InterfaceName;
            files.Add(new GeneratedFile(fileName + ".g.cs", builder.ToString()));
        }

        return files;
    }

    /// <summary>新建文件缓冲：先写 auto-generated 头、固定 using 与 namespace 声明，后续内容由调用方追加。</summary>
    private StringBuilder NewFileBuilder()
    {
        var builder = new StringBuilder();
        AppendHeader(builder);
        AppendUsings(builder);
        AppendNamespace(builder);
        return builder;
    }

    /// <summary>按生成形态把一个分组渲染成请求模型（模型式）或接口（接口式）。</summary>
    private void AppendGroup(StringBuilder builder, ApiGroup group)
    {
        // 模型式生成请求类，接口式生成代理接口。
        if (_options.Style == ApiStyle.Model)
        {
            AppendRequests(builder, group);
        }
        else
        {
            AppendInterface(builder, group);
        }
    }

    /// <summary>写文件头：auto-generated 标记（供覆盖保护识别）、工具版本、源文档标题与版本，以及 NRT 开关。</summary>
    private void AppendHeader(StringBuilder builder)
    {
        builder.Append("// <auto-generated />\n");
        builder.Append("// Generated by axiosnet-gen ").Append(_toolVersion).Append(" from \"")
            .Append(EscapeString(_spec.Title));

        if (_spec.SpecVersion.Length > 0)
        {
            builder.Append(' ').Append(EscapeString(_spec.SpecVersion));
        }

        builder.Append("\". Do not edit.\n");
        builder.Append("#nullable enable\n\n");
    }

    /// <summary>写生成代码固定依赖的 using：运行时命名空间加 System.Text.Json 序列化相关。</summary>
    private static void AppendUsings(StringBuilder builder)
    {
        builder.Append("using System;\n");
        builder.Append("using System.Collections.Generic;\n");
        builder.Append("using System.Text.Json;\n");
        builder.Append("using System.Text.Json.Serialization;\n");
        builder.Append("using System.Threading;\n");
        builder.Append("using System.Threading.Tasks;\n");
        builder.Append("using AxiosNet;\n");
        builder.Append("using AxiosNet.WebAPI;\n\n");
    }

    /// <summary>写文件级命名空间声明（已由选项解析阶段校验过合法性）。</summary>
    private void AppendNamespace(StringBuilder builder)
        => builder.Append("namespace ").Append(_options.Namespace).Append(";\n\n");

    /// <summary>按类型种类依次渲染所有模型（类 / 枚举 / 常量类），类型之间空一行。</summary>
    private void AppendModels(StringBuilder builder)
    {
        if (_spec.Types.Count == 0)
        {
            return;
        }

        // 按类型名序数排序，保证同一输入多次生成得到完全一致的文本。
        var types = _spec.Types.OrderBy(type => type.Name, StringComparer.Ordinal).ToList();
        for (var index = 0; index < types.Count; index++)
        {
            var type = types[index];
            switch (type.Kind)
            {
                case ApiTypeKind.Class:
                    AppendClass(builder, type);
                    break;
                case ApiTypeKind.Enum:
                    AppendEnum(builder, type);
                    break;
                default:
                    AppendConstants(builder, type);
                    break;
            }

            if (index < types.Count - 1)
            {
                builder.Append('\n');
            }
        }
    }

    /// <summary>渲染一个对象模型：每个属性带 JSON 名映射，非必填引用类型标可空。</summary>
    private static void AppendClass(StringBuilder builder, ApiType type)
    {
        AppendDoc(builder, type.Description, string.Empty);
        builder.Append("public sealed class ").Append(type.Name).Append('\n').Append("{\n");

        foreach (var property in type.Properties)
        {
            AppendDoc(builder, property.Description, "    ");

            if (property.IsExtensionData)
            {
                builder.Append("    [JsonExtensionData]\n");
            }
            else
            {
                builder.Append("    [JsonPropertyName(\"").Append(EscapeString(property.WireName)).Append("\")]\n");
            }

            // 非必填或类型本身可空才写成可空；必填引用类型还要补 default! 才能满足非空引用约定。
            var nullable = !property.Required || property.Type.Nullable;
            builder.Append("    public ")
                .Append(FormatType(property.Type, nullable))
                .Append(' ')
                .Append(property.Name)
                .Append(" { get; set; }");

            if (!nullable && !property.Type.IsValueType)
            {
                builder.Append(" = default!;");
            }

            builder.Append('\n');
        }

        builder.Append("}\n");
    }

    /// <summary>渲染字符串枚举：挂 <c>JsonStringEnumConverter</c>，成员名由读取阶段保证合法。</summary>
    private static void AppendEnum(StringBuilder builder, ApiType type)
    {
        AppendDoc(builder, type.Description, string.Empty);
        builder.Append("[JsonConverter(typeof(JsonStringEnumConverter))]\n");
        builder.Append("public enum ").Append(type.Name).Append('\n').Append("{\n");

        for (var index = 0; index < type.EnumMembers.Count; index++)
        {
            builder.Append("    ").Append(type.EnumMembers[index].Name);
            if (index < type.EnumMembers.Count - 1)
            {
                builder.Append(',');
            }

            builder.Append('\n');
        }

        builder.Append("}\n");
    }

    /// <summary>渲染常量类：枚举字面量不能直接做成员名时，用 <c>const string</c> 保留原始线上值。</summary>
    private static void AppendConstants(StringBuilder builder, ApiType type)
    {
        AppendDoc(builder, type.Description, string.Empty);
        builder.Append("public static class ").Append(type.Name).Append('\n').Append("{\n");

        foreach (var constant in type.Constants)
        {
            builder.Append("    public const string ").Append(constant.Name)
                .Append(" = \"").Append(EscapeString(constant.Value)).Append("\";\n");
        }

        builder.Append("}\n");
    }

    /// <summary>渲染接口式分组：组级授权提到接口上，方法之间空一行。</summary>
    private void AppendInterface(StringBuilder builder, ApiGroup group)
    {
        AppendDoc(builder, group.Description, string.Empty);

        if (group.InterfaceAuthorize)
        {
            builder.Append(AuthorizeAttribute(group.AuthScheme)).Append('\n');
        }

        builder.Append("public interface ").Append(group.InterfaceName).Append('\n').Append("{\n");

        for (var index = 0; index < group.Operations.Count; index++)
        {
            AppendMethod(builder, group.Operations[index]);
            if (index < group.Operations.Count - 1)
            {
                builder.Append('\n');
            }
        }

        builder.Append("}\n");
    }

    /// <summary>渲染模型式分组：把组内每个操作生成一个请求模型类。</summary>
    private void AppendRequests(StringBuilder builder, ApiGroup group)
    {
        for (var index = 0; index < group.Operations.Count; index++)
        {
            AppendRequest(builder, group.Operations[index]);
            if (index < group.Operations.Count - 1)
            {
                builder.Append('\n');
            }
        }
    }

    /// <summary>一个操作 → 一个 <c>ApiRequest&lt;T&gt;</c> 请求模型：路由在类上，绑定在属性上。</summary>
    private void AppendRequest(StringBuilder builder, ApiOperation operation)
    {
        AppendDoc(builder, MethodDoc(operation), string.Empty);

        if (operation.StreamFormat is not null)
        {
            builder.Append("/// <remarks>流式响应：<c>client.RequestStreamAsync(new ")
                .Append(operation.ClassName).Append("(), ").Append(operation.ClassName)
                .Append(".StreamFormat)</c> 逐帧读取。</remarks>\n");
        }
        else if (operation.ResponseVoid)
        {
            builder.Append("/// <remarks>声明没有响应正文：<c>client.RequestAsync(new ")
                .Append(operation.ClassName).Append("())</c> 的 <c>Data</c> 通常为 <c>null</c>。</remarks>\n");
        }

        if (operation.Deprecated)
        {
            builder.Append("[Obsolete(\"Deprecated in the OpenAPI document.\")]\n");
        }

        builder.Append(RouteAttribute(operation)).Append('\n');

        if (operation.RequestBody is { IsMultipart: true })
        {
            builder.Append("[Multipart]\n");
        }

        if (operation.EmitAuthorize)
        {
            builder.Append(AuthorizeAttribute(operation.AuthScheme ?? "Bearer")).Append('\n');
        }

        if (operation.Anonymous)
        {
            builder.Append("[AllowAnonymous]\n");
        }

        builder.Append("public sealed class ").Append(operation.ClassName)
            .Append(" : ApiRequest<").Append(RequestResponseType(operation)).Append(">\n{\n");

        // 类体成员逐段生成后统一拼接，段与段之间空一行。
        var members = new List<string>();

        // 已占用的属性名集合：类名、框架约定的 Configure/StreamFormat，以及后续逐个加入的参数名。
        var usedNames = new HashSet<string>(StringComparer.Ordinal)
        {
            operation.ClassName, "Configure", "StreamFormat"
        };

        foreach (var parameter in operation.Parameters)
        {
            // 属性名是线上键名的取值来源：不显式写名称时运行时用属性名，大小写不同必须写成 [Query("role")]。
            var name = Naming.Unique(Naming.Pascal(parameter.Name), usedNames);
            members.Add(RequestProperty(
                parameter.Description,
                ParameterAttribute(parameter, name),
                parameter.Type,
                name,
                !parameter.Required || parameter.Type.Nullable));
        }

        if (operation.RequestBody is { IsMultipart: true } multipart)
        {
            foreach (var part in multipart.Parts)
            {
                var name = Naming.Unique(Naming.Pascal(part.Name), usedNames);
                members.Add(RequestProperty(
                    part.Description,
                    PartAttribute(part, name),
                    part.Type,
                    name,
                    !part.Required || part.Type.Nullable));
            }
        }
        else if (operation.RequestBody is { } body)
        {
            members.Add(RequestProperty(
                body.Description,
                "[Body]",
                body.Type,
                Naming.Unique(Naming.Pascal(body.BodyName), usedNames),
                !body.Required || body.Type.Nullable));
        }

        // 模型式没有方法级特性，媒体类型与集合格式只能写进 Configure 重写。
        var configure = ConfigureLines(operation);
        if (configure.Count > 0)
        {
            var text = new StringBuilder();
            text.Append("    protected override void Configure(AxiosConfig config)\n    {\n");
            foreach (var line in configure)
            {
                text.Append("        ").Append(line).Append('\n');
            }

            text.Append("    }");
            members.Add(text.ToString());
        }

        if (operation.StreamFormat is not null)
        {
            // [Stream] 是方法级特性，请求模型改用常量：client.RequestStreamAsync(new X(), X.StreamFormat)。
            members.Add("    public const AxiosStreamFormat StreamFormat = AxiosStreamFormat."
                        + operation.StreamFormat + ";");
        }

        for (var index = 0; index < members.Count; index++)
        {
            if (index > 0)
            {
                builder.Append('\n');
            }

            builder.Append(members[index]).Append('\n');
        }

        builder.Append("}\n");
    }

    /// <summary>拼一个请求模型属性：可选 XML 注释 + 绑定特性 + 属性声明，必填引用类型补 <c>default!</c>。</summary>
    private static string RequestProperty(string? description, string attribute, TypeRef type, string name, bool nullable)
    {
        var builder = new StringBuilder();
        if (DocText(description) is { } doc)
        {
            builder.Append("    /// <summary>").Append(doc).Append("</summary>\n");
        }

        builder.Append("    ").Append(attribute).Append('\n');
        builder.Append("    public ").Append(FormatType(type, nullable)).Append(' ').Append(name).Append(" { get; set; }");

        if (!nullable && !type.IsValueType)
        {
            builder.Append(" = default!;");
        }

        return builder.ToString();
    }

    /// <summary>模型式没有方法级特性：请求体媒体类型与查询集合格式改由 <c>Configure</c> 落到本次请求上。</summary>
    private static List<string> ConfigureLines(ApiOperation operation)
    {
        // 需要落到 Configure 里的语句；为空时连 Configure 重写方法都不生成。
        var lines = new List<string>();

        if (operation.RequestBody is { IsMultipart: false } body && !IsJsonMedia(body.MediaType))
        {
            lines.Add("config.ContentType = \"" + EscapeString(body.MediaType) + "\";");
        }

        if (operation.CollectionFormat is not null)
        {
            lines.Add("config.Serialization.CollectionFormat = AxiosCollectionFormat."
                      + operation.CollectionFormat + ";");
        }

        return lines;
    }

    /// <summary>请求模型的泛型参数：流式取单帧类型，无正文固定 <c>object</c>（与 <c>AxiosResponse.Data</c> 同形）。</summary>
    private static string RequestResponseType(ApiOperation operation)
    {
        if (operation.ResponseKind == ApiResponseKind.Stream)
        {
            // 流式的泛型参数是单帧类型，不是整个流。
            var frame = operation.ReturnType ?? TypeRef.JsonElement;
            return FormatType(frame, frame.Nullable);
        }

        if (operation.ResponseVoid)
        {
            return "object";
        }

        var type = operation.ReturnType ?? TypeRef.JsonElement;
        return FormatType(type, type.Nullable);
    }

    /// <summary>渲染接口方法：注释、路由/流式/集合格式/正文类型/授权等特性，再写签名与参数列表。</summary>
    private void AppendMethod(StringBuilder builder, ApiOperation operation)
    {
        AppendDoc(builder, MethodDoc(operation), "    ");

        if (operation.Deprecated)
        {
            builder.Append("    [Obsolete(\"Deprecated in the OpenAPI document.\")]\n");
        }

        builder.Append("    ").Append(RouteAttribute(operation)).Append('\n');

        if (operation.StreamFormat is not null)
        {
            builder.Append("    [Stream(AxiosStreamFormat.").Append(operation.StreamFormat).Append(")]\n");
        }

        if (operation.CollectionFormat is not null)
        {
            builder.Append("    [QueryCollectionFormat(AxiosCollectionFormat.")
                .Append(operation.CollectionFormat).Append(")]\n");
        }

        if (operation.RequestBody is { IsMultipart: false } body && !IsJsonMedia(body.MediaType))
        {
            builder.Append("    [BodyContentType(\"").Append(EscapeString(body.MediaType)).Append("\")]\n");
        }

        if (operation.RequestBody is { IsMultipart: true })
        {
            builder.Append("    [Multipart]\n");
        }

        if (operation.EmitAuthorize)
        {
            builder.Append("    ").Append(AuthorizeAttribute(operation.AuthScheme ?? "Bearer")).Append('\n');
        }

        if (operation.Anonymous)
        {
            builder.Append("    [AllowAnonymous]\n");
        }

        builder.Append("    ").Append(ReturnType(operation)).Append(' ').Append(operation.Name).Append("(\n");

        foreach (var line in ParameterLines(operation))
        {
            builder.Append("        ").Append(line).Append(",\n");
        }

        builder.Append("        CancellationToken cancellationToken = default);\n");
    }

    /// <summary>逐行产出接口参数声明（path/query/header → multipart 部件或单个 body），末尾的取消令牌由调用方追加。</summary>
    private IEnumerable<string> ParameterLines(ApiOperation operation)
    {
        foreach (var parameter in operation.Parameters)
        {
            yield return ParameterAttribute(parameter)
                         + " "
                         + FormatType(parameter.Type, !parameter.Required || parameter.Type.Nullable)
                         + " "
                         + parameter.Name;
        }

        if (operation.RequestBody is { IsMultipart: true } multipart)
        {
            foreach (var part in multipart.Parts)
            {
                yield return PartAttribute(part)
                             + " "
                             + FormatType(part.Type, !part.Required || part.Type.Nullable)
                             + " "
                             + part.Name;
            }
        }
        else if (operation.RequestBody is { } body)
        {
            yield return "[Body] "
                         + FormatType(body.Type, !body.Required || body.Type.Nullable)
                         + " "
                         + body.BodyName;
        }
    }

    /// <summary>接口方法的返回类型：流式取异步帧序列，无正文按是否包装响应区分，其余按强类型正文。</summary>
    private string ReturnType(ApiOperation operation)
    {
        if (operation.ResponseKind == ApiResponseKind.Stream)
        {
            // 流式返回 AsyncEnumerable 包装：调用方可以逐帧 await foreach。
            var frame = operation.ReturnType ?? TypeRef.JsonElement;
            return $"Task<AxiosResponse<IAsyncEnumerable<{FormatType(frame, frame.Nullable)}>>>";
        }

        if (operation.ResponseVoid)
        {
            return _options.UseResponseWrapper ? "Task<AxiosResponse>" : "Task";
        }

        var type = FormatType(operation.ReturnType ?? TypeRef.JsonElement, operation.ReturnType?.Nullable == true);
        return _options.UseResponseWrapper ? $"Task<AxiosResponse<{type}>>" : $"Task<{type}>";
    }

    /// <summary>把类型引用格式化成可写进源码的类型名（必要时追加 <c>?</c>）。</summary>
    private static string FormatType(TypeRef type, bool nullable) => type.Format(nullable);

    /// <summary>按 HTTP 方法选路由特性：常见动词用 <c>[Get]</c> 等，其余退回 <c>[HttpApi(method, path)]</c>。</summary>
    private static string RouteAttribute(ApiOperation operation)
        => operation.Method switch
        {
            "GET" => $"[Get(\"{EscapeString(operation.Path)}\")]",
            "POST" => $"[Post(\"{EscapeString(operation.Path)}\")]",
            "PUT" => $"[Put(\"{EscapeString(operation.Path)}\")]",
            "PATCH" => $"[Patch(\"{EscapeString(operation.Path)}\")]",
            "DELETE" => $"[Delete(\"{EscapeString(operation.Path)}\")]",
            "HEAD" => $"[Head(\"{EscapeString(operation.Path)}\")]",
            "OPTIONS" => $"[Options(\"{EscapeString(operation.Path)}\")]",
            _ => $"[HttpApi(\"{EscapeString(operation.Method)}\", \"{EscapeString(operation.Path)}\")]"
        };

    /// <summary>生成授权特性：Bearer 用无参 <c>[Authorize]</c>，其他 scheme 显式写出名字。</summary>
    private static string AuthorizeAttribute(string scheme)
        => scheme.Equals("Bearer", StringComparison.OrdinalIgnoreCase)
            ? "[Authorize]"
            : $"[Authorize(\"{EscapeString(scheme)}\")]";

    /// <summary>以成员名作为线上键名生成绑定特性（模型式外部无法改属性名，故直接等于成员名）。</summary>
    private static string ParameterAttribute(ApiParameter parameter)
        => ParameterAttribute(parameter, parameter.Name);

    /// <summary>按位置选 <c>[Path]</c> / <c>[Query]</c> / <c>[Header]</c>；成员名与线上键名不一致时显式写出键名。</summary>
    private static string ParameterAttribute(ApiParameter parameter, string memberName)
    {
        // 位置枚举到特性名的一一映射。
        var name = parameter.Location switch
        {
            ApiParameterLocation.Path => "Path",
            ApiParameterLocation.Query => "Query",
            _ => "Header"
        };

        // Path / Query 的键名按 OpenAPI 规范区分大小写；Header 由 HTTP 规定不区分，省略参数名才安全。
        var comparison = parameter.Location == ApiParameterLocation.Header
            ? StringComparison.OrdinalIgnoreCase
            : StringComparison.Ordinal;

        return MatchesWire(parameter.WireName, memberName, comparison)
            ? $"[{name}]"
            : $"[{name}(\"{EscapeString(parameter.WireName)}\")]";
    }

    /// <summary>以成员名作为部件名生成 <c>[Part]</c>（模型式下名称可能已被去重改写）。</summary>
    private static string PartAttribute(ApiPart part)
        => PartAttribute(part, part.Name);

    /// <summary>按成员名生成 <c>[Part]</c>；成员名与部件名不一致时显式写出线上字段名。</summary>
    private static string PartAttribute(ApiPart part, string memberName)
        // 部件名写进 Content-Disposition，服务端按原样匹配，大小写不同也必须显式写出。
        => MatchesWire(part.WireName, memberName, StringComparison.Ordinal)
            ? "[Part]"
            : $"[Part(\"{EscapeString(part.WireName)}\")]";

    /// <summary>判断成员名（去掉关键字转义前缀 <c>@</c> 后）是否与线上键名一致，一致即可省略特性参数。</summary>
    private static bool MatchesWire(string wireName, string parameterName, StringComparison comparison)
    {
        // 关键字转义写法（如 @class）在运行时对应无前缀的标识符。
        var name = parameterName.StartsWith('@') ? parameterName[1..] : parameterName;
        return string.Equals(wireName, name, comparison);
    }

    /// <summary>
    /// 判断媒体类型是否默认按 JSON 发送、无需显式 Content-Type：只有精确的 <c>application/json</c> 与通配 <c>*/*</c>。
    /// <c>+json</c> 等结构化后缀虽然也用 JSON 序列化，但线上 Content-Type 必须按声明发送，不能省略。
    /// </summary>
    private static bool IsJsonMedia(string media)
        => media.Equals("application/json", StringComparison.OrdinalIgnoreCase)
           || media == "*/*";

    /// <summary>拼方法注释正文：方法 + 路径，再追加摘要，摘要与说明不同时才补说明。</summary>
    private static string MethodDoc(ApiOperation operation)
    {
        // 注释以「METHOD path」开头，方便在 IDE 里定位到具体操作。
        var text = $"{operation.Method} {operation.Path}";
        if (!string.IsNullOrWhiteSpace(operation.Summary))
        {
            text += " — " + operation.Summary.Trim();
        }

        if (!string.IsNullOrWhiteSpace(operation.Description)
            && !string.Equals(operation.Description.Trim(), operation.Summary?.Trim(), StringComparison.Ordinal))
        {
            text += " " + operation.Description.Trim();
        }

        return text;
    }

    /// <summary>按缩进追加一行 XML 摘要注释；文本为空或全空白时什么都不写。</summary>
    private static void AppendDoc(StringBuilder builder, string? text, string indent)
    {
        var doc = DocText(text);
        if (doc is null)
        {
            return;
        }

        builder.Append(indent).Append("/// <summary>").Append(doc).Append("</summary>\n");
    }

    /// <summary>把任意文档文本压成单行并做 XML 转义；全空白返回 null，避免生成空注释。</summary>
    private static string? DocText(string? text)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return null;
        }

        var builder = new StringBuilder(text.Length);

        // 标记上一次遇到过空白但尚未输出：只有后面还有非空白字符时才补一个空格。
        var pendingSpace = false;

        foreach (var c in text)
        {
            if (char.IsWhiteSpace(c))
            {
                pendingSpace = true;
                continue;
            }

            if (pendingSpace && builder.Length > 0)
            {
                builder.Append(' ');
            }

            pendingSpace = false;

            switch (c)
            {
                case '&':
                    builder.Append("&amp;");
                    break;
                case '<':
                    builder.Append("&lt;");
                    break;
                case '>':
                    builder.Append("&gt;");
                    break;
                default:
                    // 控制字符（除已被压成空白的 \t / 换行等）会破坏 XML 注释（CS1570），统一替换成空格。
                    builder.Append(char.IsControl(c) ? ' ' : c);
                    break;
            }
        }

        return builder.Length == 0 ? null : builder.ToString();
    }

    /// <summary>
    /// 转义 C# 字符串字面量里的特殊字符：反斜杠、双引号、常见换行 / 制表符，以及 C# 视为行终止符的控制字符。
    /// U+0085 / U+2028 / U+2029 与其它控制字符必须写成 <c>\uXXXX</c>，否则生成的源码本身无法编译。
    /// </summary>
    private static string EscapeString(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var c in value)
        {
            switch (c)
            {
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\r':
                    builder.Append("\\r");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                default:
                    if (c < 0x20 || c == '\u0085' || c == '\u2028' || c == '\u2029')
                    {
                        builder.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(c);
                    }

                    break;
            }
        }

        return builder.ToString();
    }
