namespace AxiosNet;

// AxiosClient 的快捷方法层：与 axios.get/post/put/patch/delete/head/options
// 以及 postForm/putForm/patchForm 一一对应的重载，只负责组装 AxiosConfig。
public sealed partial class AxiosClient
