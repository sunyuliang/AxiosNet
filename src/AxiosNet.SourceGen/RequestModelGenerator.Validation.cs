using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;

namespace AxiosNet.SourceGen
{
    /// <summary>
    /// 校验入口生成：把本程序集里源生成器覆盖到的请求模型与接口烘焙成一个静态 <c>ValidateAll()</c>，
    /// 启动期调用即能拿到全部声明错误；Native AOT 下不依赖程序集扫描。
    /// </summary>
    public sealed partial class RequestModelGenerator
    {
        private const string ValidationNamespace = "AxiosNet.Generated";

        private static void InitializeValidation(
            IncrementalGeneratorInitializationContext context,
            IncrementalValueProvider<ImmutableArray<RequestModelInfo>> models,
            IncrementalValueProvider<ImmutableArray<InterfaceModelInfo>> interfaces,
            IncrementalValueProvider<GeneratorOptions> options)
        {
            var assemblyName = context.CompilationProvider.Select(static (compilation, _) => compilation.AssemblyName);

            context.RegisterSourceOutput(
                models.Combine(interfaces).Combine(options).Combine(assemblyName),
                static (output, data) => ExecuteValidation(
                    output,
                    data.Left.Left.Left,
                    data.Left.Left.Right,
                    data.Left.Right,
                    data.Right));
        }

        private static void ExecuteValidation(
            SourceProductionContext context,
            ImmutableArray<RequestModelInfo> models,
            ImmutableArray<InterfaceModelInfo> interfaces,
            GeneratorOptions options,
            string? assemblyName)
        {
            if (!options.Enabled)
            {
                // AXA012 由请求模型管线统一报告。
                return;
            }

            // 与生成管线保持一致：先按类型名去重，再判断是否可生成（首个声明不可生成时不改由后续同名声明的副本兜底）。
            // 模型与接口各自去重：它们虽是同一编译的两条流，混用一个集合会让同名（不同种类）声明互相吞掉。
            var seenModels = new HashSet<string>(StringComparer.Ordinal);
            var requestTypes = new List<string>();
            foreach (var model in models)
            {
                if (seenModels.Add(model.FullTypeName) && model.Emit)
                {
                    requestTypes.Add(model.FullTypeName);
                }
            }

            var seenInterfaces = new HashSet<string>(StringComparer.Ordinal);
            var interfaceTypes = new List<string>();
            foreach (var model in interfaces)
            {
                if (seenInterfaces.Add(model.FullTypeName) && model.Emit)
                {
                    interfaceTypes.Add(model.FullTypeName);
                }
            }

            if (requestTypes.Count == 0 && interfaceTypes.Count == 0)
            {
                return;
            }

            var className = "AxiosNetValidation_" + SanitizeIdentifier(assemblyName);
            context.AddSource(
                "AxiosNet.Validation." + className + ".g.cs",
                Emit(className, requestTypes, interfaceTypes));
        }

        private static string Emit(string className, List<string> requestTypes, List<string> interfaceTypes)
        {
            var builder = new StringBuilder(2048);
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable disable");
            builder.AppendLine();
            builder.Append("namespace ").AppendLine(ValidationNamespace);
            builder.AppendLine("{");
            builder.Append("    [global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"")
                .Append(GeneratorName)
                .Append("\", \"")
                .Append(GeneratorVersion)
                .AppendLine("\")]");
            builder.Append("    public static class ").AppendLine(className);
            builder.AppendLine("    {");
            builder.AppendLine("        /// <summary>校验本程序集里源生成器覆盖到的全部请求模型与接口，返回全部错误（空列表 = 合法）。</summary>");
            builder.AppendLine("        public static global::System.Collections.Generic.IReadOnlyList<string> ValidateAll()");
            builder.AppendLine("        {");
            builder.AppendLine("            var errors = new global::System.Collections.Generic.List<string>();");

            if (requestTypes.Count > 0)
            {
                AppendValidationCall(builder, "ValidateModels", requestTypes);
            }

            if (interfaceTypes.Count > 0)
            {
                AppendValidationCall(builder, "ValidateInterfaces", interfaceTypes);
            }

            builder.AppendLine("            return errors;");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        /// <summary>
        /// 单个 <c>ValidateAll</c> 方法的体积上限：每个 <c>typeof(T)</c> 都要进方法体，
        /// 全塞进一次调用在大程序集（上千个模型）上会长到编译器拒绝的程度，按批切开。
        /// </summary>
        private const int ValidationBatchSize = 100;

        private static void AppendValidationCall(StringBuilder builder, string method, List<string> typeNames)
        {
            for (var start = 0; start < typeNames.Count; start += ValidationBatchSize)
            {
                var end = Math.Min(start + ValidationBatchSize, typeNames.Count);
                builder.Append("            errors.AddRange(global::AxiosNet.WebAPI.ApiClient.")
                    .Append(method)
                    .AppendLine("(");

                for (var i = start; i < end; i++)
                {
                    builder.Append("                typeof(").Append(typeNames[i]).Append(')');
                    builder.AppendLine(i == end - 1 ? "));" : ",");
                }
            }
        }

        /// <summary>程序集名 → C# 标识符：非字母 / 数字 / 下划线一律替换成下划线。</summary>
        private static string SanitizeIdentifier(string? assemblyName)
        {
            if (string.IsNullOrEmpty(assemblyName))
            {
                return "Assembly";
            }

            var name = assemblyName!;
            var builder = new StringBuilder(name.Length);
            foreach (var ch in name)
            {
                builder.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
            }

            return builder.Length == 0 || !char.IsDigit(builder[0]) ? builder.ToString() : "_" + builder;
        }
    }
}
