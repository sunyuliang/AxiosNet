using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AxiosNet.SourceGen
{
    /// <summary>
    /// 消费方编译里的 <c>ModuleInitializerAttribute</c> 补位。
    /// </summary>
    /// <remarks>
    /// 生成代码用 <c>[global::System.Runtime.CompilerServices.ModuleInitializerAttribute]</c> 挂注册方法，
    /// 而 .NET Framework / .NET Core 3.x 的 BCL 没有这个类型。AxiosNet 的兼容资产里有一份 <c>internal</c> 版本，
    /// 但 internal 跨程序集不可见，直接引用是 CS0122；把库里的那份改成 public 又会让
    /// 「引用兼容资产的 net5+ 编译」出现两份同名公共类型（CS0433）。
    /// 因此补位必须落在消费方自己的编译里：这里按需生成一份同名 internal 声明。
    /// </remarks>
    internal static class ModuleInitializerShim
    {
        /// <summary>补位类型的元数据全名。</summary>
        internal const string TypeName = "System.Runtime.CompilerServices.ModuleInitializerAttribute";

        /// <summary>生成文件的 hint 名。</summary>
        internal const string HintName = "AxiosNet.GeneratedModuleInitializer.g.cs";

        /// <summary>判断该编译是否需要补一份可见的模块初始化器标记。</summary>
        /// <param name="compilation">消费方编译。</param>
        /// <returns>需要补位时为 <c>true</c>。</returns>
        internal static bool IsRequired(Compilation compilation)
        {
            var existing = compilation.GetTypeByMetadataName(TypeName);

            // null 有两种情形：编译里根本没有（生成代码也不会用到），或同名类型有歧义
            // （BCL 公开版与兼容资产 internal 版并存 / 消费方自带 PolySharp）。两种都能正常绑定，不补。
            if (existing is null)
            {
                return false;
            }

            // 公开可见，或消费方自己就在源码里定义过：直接用既有的，补一份只会冲突。
            return existing.DeclaredAccessibility != Accessibility.Public
                && !existing.Locations.Any(static location => location.IsInSource);
        }

        /// <summary>生成补位声明：internal、无成员，只作编译期标记。</summary>
        internal static SourceText Emit()
            => SourceText.From(
                "// <auto-generated/>\n"
                + "#nullable disable\n\n"
                + "namespace System.Runtime.CompilerServices\n"
                + "{\n"
                + "    [global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]\n"
                + "    internal sealed class ModuleInitializerAttribute : global::System.Attribute\n"
                + "    {\n"
                + "    }\n"
                + "}\n",
                Encoding.UTF8);
    }
}
