using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace AxiosNet.SourceGen
{
    /// <summary>把 <see cref="ShapeInfo"/> 写成模块初始化器里的形状注册代码（命名类型用 <c>default(T)</c>、匿名类型用结构相同的样本推断类型参数）。</summary>
    internal static class ShapeEmitter
    {
        public static string Emit(ShapeInfo shape)
        {
            var builder = new StringBuilder(1024);
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable disable");
            builder.AppendLine();
            builder.AppendLine("namespace AxiosNet.Generated");
            builder.AppendLine("{");
            builder.Append("    [global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"")
                .Append(RequestModelGenerator.GeneratorName)
                .Append("\", \"")
                .Append(RequestModelGenerator.GeneratorVersion)
                .AppendLine("\")]");
            builder.Append("    internal static class ").AppendLine(shape.ClassName);
            builder.AppendLine("    {");
            builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializerAttribute]");
            builder.AppendLine("        internal static void Register()");
            builder.AppendLine("        {");
            if (shape.RegisterShape)
            {
                builder.AppendLine("            global::AxiosNet.Metadata.AxiosMetadata.RegisterGeneratedShapeFromSample(");
                builder.Append("                ")
                    .Append(shape.SampleExpression ?? "default(" + shape.TypeExpression + ")")
                    .AppendLine(",");
                builder.AppendLine("                static b =>");
                builder.AppendLine("                {");
                foreach (var member in shape.Members)
                {
                    builder.Append("                    b.Member(")
                        .Append(Literal(member.Name))
                        .Append(", ")
                        .Append(Literal(member.FieldName))
                        .Append(", ")
                        .Append(member.Ignored ? "true" : "false")
                        .Append(", ")
                        .Append(member.GetterExpression)
                        .AppendLine(");");
                }

                builder.AppendLine("                });");
            }

            if (shape.MapInterfaceExpression is { } mapInterface)
            {
                builder.AppendLine("            global::AxiosNet.Metadata.AxiosMetadata.RegisterGeneratedMap(");
                builder.Append("                typeof(").Append(shape.TypeExpression).AppendLine("),");
                builder.Append("                static d => Enumerate((").Append(shape.TypeExpression).AppendLine(")d));");
            }

            builder.AppendLine("        }");

            if (shape.MapInterfaceExpression is { } mapContract)
            {
                builder.AppendLine();
                builder.Append("        private static global::System.Collections.Generic.IEnumerable<global::System.Collections.Generic.KeyValuePair<string, object>> Enumerate(")
                    .Append(shape.TypeExpression)
                    .AppendLine(" map)");
                builder.AppendLine("        {");
                builder.Append("            foreach (var entry in ((")
                    .Append(mapContract)
                    .AppendLine(")map))");
                builder.AppendLine("            {");
                builder.AppendLine("                yield return new global::System.Collections.Generic.KeyValuePair<string, object>(entry.Key, entry.Value);");
                builder.AppendLine("            }");
                builder.AppendLine("        }");
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");

            return builder.ToString();
        }

        private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
    }
}
